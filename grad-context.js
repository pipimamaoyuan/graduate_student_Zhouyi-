// 白名单（后端校验用）
const AUDIENCE_KEYS = AUDIENCES.map((a) => a.key);
const SCENARIOS = [...new Set(AUDIENCES.flatMap((a) => a.scenarios.map((s) => s.key)))];

function findAudience(key) {
  return AUDIENCES.find((a) => a.key === key);
}

function buildAutoPrompt() {
  return AUDIENCES.map((audience) => {
    const list = audience.scenarios.map((s) => `· ${s.label}：${s.keywords}`).join("\n");
    const guides = audience.scenarios.map((s) => `· ${s.label}：${s.guide}`).join("\n");
    return [
      audience.persona,
      `请判断用户是否属于「${audience.label}」以及属于其中哪个场景，再按该场景的解读角度展开：`,
      list,
      "",
      "各场景解读原则：",
      guides
    ].join("\n");
  }).join("\n\n");
}

// 根据人群与场景构建提示词片段；未命中时优雅回退到「自动识别」。
function buildScenarioPrompt(audienceKey, scenarioKey) {
  const audience = findAudience(audienceKey);
  if (!audience) return buildAutoPrompt();

  const scenario = audience.scenarios.find((s) => s.key === scenarioKey);
  if (scenario) {
    return [
      audience.persona,
      "",
      `用户已选择人群为「${audience.label}」，问题场景为「${scenario.label}」，请直接按该场景的解读角度展开：`,
      scenario.guide
    ].join("\n");
  }

  const list = audience.scenarios.map((s) => `· ${s.label}：${s.keywords}`).join("\n");
  const guides = audience.scenarios.map((s) => `· ${s.label}：${s.guide}`).join("\n");
  return [
    audience.persona,
    "",
    `用户已选择人群为「${audience.label}」，请先判断其问题属于以下哪个场景，再按该场景的解读角度展开：`,
    list,
    "",
    "各场景解读原则：",
    guides
  ].join("\n");
}

